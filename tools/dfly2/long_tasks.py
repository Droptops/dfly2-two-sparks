def api_specification(sections, seed):
    rng = Lcg(seed)
    out = ["Ledgerline Payments API, integration specification, revision 7. Every section is normative."]
    for number in range(1, sections + 1):
        if number == 3:
            out.append(TRANSFER_SECTION)
            continue
        resource = RESOURCES[(number - 1) % len(RESOURCES)]
        revisit = ", continued" if number > len(RESOURCES) else ""
        rules = []
        start = rng.between(0, len(SPEC_RULES) - 1)
        for offset in range(rng.between(3, 4)):
            rules.append(SPEC_RULES[(start + offset) % len(SPEC_RULES)].format(
                resource=resource, hours=rng.pick([12, 24, 48, 72]), page=rng.pick([50, 100, 200, 500]),
                minutes=rng.pick([5, 10, 15, 30, 300]), amount=rng.pick([1000, 5000, 25000]),
                days=rng.pick([30, 90, 365])))
        out.append(f"Section {number}. {resource.capitalize()}{revisit}. " + " ".join(rules))
    return "\n\n".join(out)


