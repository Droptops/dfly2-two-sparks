def meeting_notes(paragraphs, seed):
    rng = Lcg(seed)
    out = ["Programme sync notes: Harbor platform migration. These notes cover several weekly meetings in order."]
    for index in range(paragraphs):
        sentences = []
        remaining = list(OBSERVATIONS)
        for _ in range(rng.between(3, 4)):
            person = rng.pick(PEOPLE)
            other = rng.pick([p for p in PEOPLE if p != person])
            sentences.append(remaining.pop(rng.between(0, len(remaining) - 1)).format(
                person=person, other=other, stream=rng.pick(WORKSTREAMS), minutes=rng.between(12, 95),
                count=rng.between(4, 90) * 50, week=rng.between(14, 30), percent=rng.between(20, 85)))
        out.append(f"Week {index + 1}. " + " ".join(sentences))
    return "\n\n".join(out)


