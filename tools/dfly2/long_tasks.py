def python_module(functions, seed, insert_bug_at=None):
    rng = Lcg(seed)
    used = set()
    blocks = [MODULE_HEADER]
    while len(blocks) - 1 < functions:
        if insert_bug_at is not None and len(blocks) - 1 == insert_bug_at:
            blocks.append(BUGGY_FUNCTION)
            continue
        template_index, noun = rng.between(0, len(FUNCTION_TEMPLATES) - 1), rng.pick(NOUNS)
        if (template_index, noun) in used:
            continue
        used.add((template_index, noun))
        blocks.append(FUNCTION_TEMPLATES[template_index].format(
            noun=noun, limit=rng.pick([8, 16, 32, 50, 64, 100, 250]), separator=rng.pick([";", ",", "|"])))
    return "\n\n".join(blocks)


