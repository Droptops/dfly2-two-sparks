REGIONS = ["us-west-2", "us-east-1", "eu-central-1", "ap-south-1"]
FAILURES = {500: "unhandled exception", 502: "upstream timeout", 503: "pool exhausted", 504: "gateway timeout"}
CLIENT_ERRORS = {400: "invalid payload", 404: "not found", 409: "version conflict", 429: "rate limited"}


def service_log(lines, seed):
    rng = Lcg(seed)
    second = 14 * 3600 + 60
    out = []
    for index in range(lines):
        second += rng.between(1, 9)
        service = rng.pick(sorted(SERVICES))
        roll = rng.between(1, 100)
        if roll <= 70:
            status, note = rng.pick([200, 200, 200, 201, 204]), "ok"
        elif roll <= 84:
            status = rng.pick(sorted(CLIENT_ERRORS))
            note = CLIENT_ERRORS[status]
        else:
            status = rng.pick(sorted(FAILURES))
            note = FAILURES[status]
        duration = rng.between(8, 140) if status < 500 else rng.between(400, 2900)
        out.append(
            f"2026-03-14T{second // 3600:02d}:{second % 3600 // 60:02d}:{second % 60:02d}Z {service} "
            f"req=R{48000 + index * 7 + rng.between(0, 6)} route={rng.pick(SERVICES[service])} status={status} "
            f"ms={duration} region={rng.pick(REGIONS)} note=\"{note}\"")
    return "\n".join(out)


